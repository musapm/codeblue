-- Join an active course with its code. Wrong codes are counted (10 per hour), so the
-- function returns {status: 'invalid'} instead of raising (which would undo the count).
create or replace function public.academic_join_course(p_tenant_slug text, p_code text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_tenant uuid := app.tenant_id_for_slug(p_tenant_slug);
  v_code text := upper(regexp_replace(coalesce(p_code, ''), '[[:space:]-]', '', 'g'));
  c public.courses;
  v_joined boolean;
begin
  if v_tenant is null or not app.has_permission(v_tenant, 'academic.use') or not app.tenant_has_feature(v_tenant, 'academic_agent') then
    raise exception 'not authorized' using errcode = '42501';
  end if;
  if (select count(*) from app.academic_join_failures f where f.user_id = auth.uid() and f.at > now() - interval '1 hour') >= 10 then
    raise exception 'too many attempts' using errcode = '54000';
  end if;
  select * into c from public.courses
  where tenant_id = v_tenant and join_code = v_code and status = 'active' and join_open;
  if c.id is null then
    delete from app.academic_join_failures f where f.user_id = auth.uid() and f.at < now() - interval '1 hour';
    insert into app.academic_join_failures (user_id, tenant_id) values (auth.uid(), v_tenant);
    return jsonb_build_object('status', 'invalid');
  end if;
  insert into public.course_members (course_id, tenant_id, user_id, role, added_by)
  values (c.id, v_tenant, auth.uid(), 'student', auth.uid())
  on conflict (course_id, user_id) do nothing;
  v_joined := found;
  return jsonb_build_object('status', case when v_joined then 'joined' else 'already' end, 'course_id', c.id);
end;
$$;

