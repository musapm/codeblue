-- AI-generated study aids, private to the person who made them.
create table public.academic_items (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null,
  course_id uuid not null,
  user_id uuid not null references auth.users (id) on delete cascade,
  kind text not null constraint academic_items_kind check (kind in ('summary', 'quiz', 'flashcards', 'study_plan')),
  title text not null constraint academic_items_title check (char_length(btrim(title)) between 1 and 200),
  language text not null constraint academic_items_language check (language in ('en', 'ar')),
  content jsonb not null constraint academic_items_content check (jsonb_typeof(content) = 'object' and pg_column_size(content) <= 262144),
  -- Quizzes only: correct options and explanations. Never readable by clients (column grants).
