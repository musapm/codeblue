create table public.courses (
  id uuid primary key default gen_random_uuid(),
  tenant_id uuid not null references public.tenants (id) on delete cascade,
  code text not null constraint courses_code check (code ~ '^[A-Za-z0-9][A-Za-z0-9 ._-]{0,19}$'),
  title text not null constraint courses_title check (char_length(btrim(title)) between 2 and 160),
  title_ar text constraint courses_title_ar check (title_ar is null or char_length(btrim(title_ar)) between 2 and 160),
  description text constraint courses_description check (description is null or char_length(description) <= 2000),
  department_id uuid,
  term text constraint courses_term check (term is null or char_length(btrim(term)) between 1 and 40),
  status text not null default 'draft' constraint courses_status check (status in ('draft', 'active', 'archived')),
  -- Per-course enablement of the AI study tools (off until an instructor turns them on).
  ai_enabled boolean not null default false,
  allow_summaries boolean not null default true,
  allow_quizzes boolean not null default true,
  allow_flashcards boolean not null default true,
  allow_study_plans boolean not null default true,
  instructions text constraint courses_instructions check (instructions is null or char_length(instructions) <= 1000),
  join_code text not null constraint courses_join_code check (join_code ~ '^[A-Z2-9]{8}$'),
  join_open boolean not null default true,
  created_by uuid references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (tenant_id, join_code),
  unique (tenant_id, id),
  foreign key (tenant_id, department_id) references public.departments (tenant_id, id) on delete set null (department_id)
);
create unique index courses_code_term_idx on public.courses (tenant_id, lower(code), coalesce(lower(term), ''));

