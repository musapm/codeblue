-- The caller's role in a course ('instructor' | 'student'), while they are an active member of
-- an operating university that has the academic assistant.
create or replace function app.course_role(p_course uuid)
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select cm.role
  from public.course_members cm
  join public.courses c on c.id = cm.course_id
  where cm.course_id = p_course and cm.user_id = auth.uid()
    and app.is_tenant_member(c.tenant_id)
    and app.tenant_has_feature(c.tenant_id, 'academic_agent');
$$;

-- Teach (manage) a course: academic managers of its university, or its instructors (with academic.use).
create or replace function app.can_teach_course(p_course uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce((
    select app.tenant_has_feature(c.tenant_id, 'academic_agent') and (
      app.has_permission(c.tenant_id, 'academic.manage')
      or (app.course_role(c.id) = 'instructor' and app.has_permission(c.tenant_id, 'academic.use'))
    )
    from public.courses c
    where c.id = p_course
  ), false);
$$;

-- Study in a course: enrolled students with academic.use, while the course is active.
create or replace function app.is_course_student(p_course uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce((
    select c.status = 'active' and app.course_role(c.id) = 'student' and app.has_permission(c.tenant_id, 'academic.use')
    from public.courses c
    where c.id = p_course
  ), false);
$$;

create or replace function app.can_view_course(p_course uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select app.can_teach_course(p_course) or app.is_course_student(p_course);
$$;

-- A random 8-character code without look-alike characters (no I, L, O, 0, 1), unique in the university.
create or replace function app.unique_join_code(p_tenant uuid)
returns text
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  alphabet constant text := 'ABCDEFGHJKMNPQRSTUVWXYZ23456789';
  v_bytes bytea;
  v_code text;
begin
  loop
    v_bytes := extensions.gen_random_bytes(8);
    v_code := '';
    for i in 0..7 loop
      v_code := v_code || substr(alphabet, (get_byte(v_bytes, i) % 31) + 1, 1);
    end loop;
    exit when not exists (select 1 from public.courses c where c.tenant_id = p_tenant and c.join_code = v_code);
  end loop;
  return v_code;
end;
$$;

-- Does another member (not the caller) hold a permission in the university?
