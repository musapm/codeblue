  -- The materials it was generated from: [{document_id, version_no, title, title_ar}].
  sources jsonb not null default '[]'::jsonb constraint academic_items_sources check (jsonb_typeof(sources) = 'array'),
  model text not null constraint academic_items_model check (model ~ '^[a-z0-9][a-z0-9._:-]{1,79}$'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (tenant_id, id),
  foreign key (tenant_id, course_id) references public.courses (tenant_id, id) on delete cascade
);
create index academic_items_owner_idx on public.academic_items (user_id, course_id, created_at desc);
create index academic_items_course_idx on public.academic_items (course_id, created_at);

