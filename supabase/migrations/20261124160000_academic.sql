-- Check everything before a model call and return the course and the selected materials (in
-- order, up to 120,000 characters). Students use published materials; teachers any processed one.
create or replace function public.academic_begin_generation(p_course uuid, p_kind text, p_documents uuid[])
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  c public.courses;
  s public.academic_settings;
  v_max constant integer := 120000;
begin
  select * into c from public.courses where id = p_course;
  if c.id is null or not app.can_view_course(c.id) then
    raise exception 'not authorized' using errcode = '42501';
  end if;
  if c.status = 'archived' or not c.ai_enabled then
    raise exception 'study tools are off for this course' using errcode = '55000';
  end if;
  if p_kind is null or p_kind not in ('summary', 'quiz', 'flashcards', 'study_plan') then
    raise exception 'invalid kind' using errcode = '22023';
  end if;
  if not (case p_kind when 'summary' then c.allow_summaries when 'quiz' then c.allow_quizzes when 'flashcards' then c.allow_flashcards else c.allow_study_plans end) then
    raise exception 'this study tool is off for this course' using errcode = '55000';
  end if;
  if p_documents is null or coalesce(cardinality(p_documents), 0) not between 1 and 10
     or cardinality(p_documents) <> (select count(distinct x) from unnest(p_documents) as x) then
    raise exception 'choose 1 to 10 materials' using errcode = '22023';
  end if;
  if exists (
    select 1 from unnest(p_documents) as x (id)
    where not exists (
      select 1 from public.knowledge_documents d
      where d.id = x.id and d.course_id = c.id and d.current_version_id is not null and app.can_read_knowledge(d.tenant_id, d.id)
    )
  ) then
    raise exception 'material not available' using errcode = '22023';
  end if;
  select * into s from public.academic_settings where tenant_id = c.tenant_id;
  if coalesce(s.monthly_budget_usd, 0) <= app.ai_month_cost(c.tenant_id, 'academic_agent') then
    raise exception 'monthly AI budget reached' using errcode = '53400';
  end if;
  if (select count(*) from public.ai_usage_events u
      where u.tenant_id = c.tenant_id and u.user_id = auth.uid() and u.feature = 'academic_agent' and u.created_at > now() - interval '24 hours')
     >= coalesce(s.daily_limit, 20) then
    raise exception 'daily limit reached' using errcode = '54000';
  end if;

  return (
    with docs as (
      select d.id, d.title, d.title_ar, d.current_version_id, v.version_no, x.ord
      from unnest(p_documents) with ordinality as x (id, ord)
      join public.knowledge_documents d on d.id = x.id
      join public.knowledge_document_versions v on v.id = d.current_version_id
    ),
    chunks as (
      select dk.id as document_id, ch.chunk_index, ch.page_from, ch.page_to, ch.heading, ch.content,
             sum(char_length(ch.content)) over (order by dk.ord, ch.chunk_index) as running
      from docs dk
      join public.knowledge_chunks ch on ch.version_id = dk.current_version_id
    )
    select jsonb_build_object(
      'course', jsonb_build_object('code', c.code, 'title', c.title, 'title_ar', c.title_ar, 'instructions', c.instructions),
      'truncated', exists (select 1 from chunks where running > v_max),
      'materials', coalesce((
        select jsonb_agg(jsonb_build_object(
          'document_id', dk.id, 'version_no', dk.version_no, 'title', dk.title, 'title_ar', dk.title_ar,
          'chunks', coalesce((
            select jsonb_agg(jsonb_build_object('page_from', ch.page_from, 'page_to', ch.page_to, 'heading', ch.heading, 'content', ch.content)
                             order by ch.chunk_index)
            from chunks ch
            where ch.document_id = dk.id and ch.running <= v_max
          ), '[]'::jsonb)
        ) order by dk.ord)
        from docs dk
      ), '[]'::jsonb)
    )
  );
end;
$$;

-- Store a generated study aid and book its usage. The structure is checked here as well, so a
-- quiz can always be graded.
create or replace function public.academic_save_item(
  p_course uuid,
  p_kind text,
  p_title text,
  p_language text,
  p_content jsonb,
  p_answer_key jsonb,
  p_sources jsonb,
  p_model text,
  p_usage jsonb
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  c public.courses;
  v_id uuid;
  v_n integer;
begin
  select * into c from public.courses where id = p_course;
  if c.id is null or not app.can_view_course(c.id) then
    raise exception 'not authorized' using errcode = '42501';
  end if;
  if c.status = 'archived' or not c.ai_enabled then
    raise exception 'study tools are off for this course' using errcode = '55000';
  end if;
  if p_kind is null or p_kind not in ('summary', 'quiz', 'flashcards', 'study_plan')
     or jsonb_typeof(p_content) is distinct from 'object'
     or jsonb_typeof(p_sources) is distinct from 'array' or jsonb_array_length(p_sources) not between 1 and 10 then
    raise exception 'invalid study aid' using errcode = '22023';
  end if;
  v_n := case p_kind
    when 'quiz' then case when jsonb_typeof(p_content -> 'questions') = 'array' then jsonb_array_length(p_content -> 'questions') end
    when 'flashcards' then case when jsonb_typeof(p_content -> 'cards') = 'array' then jsonb_array_length(p_content -> 'cards') end
    when 'study_plan' then case when jsonb_typeof(p_content -> 'sessions') = 'array' then jsonb_array_length(p_content -> 'sessions') end
    else case when jsonb_typeof(p_content -> 'overview') = 'string' then 1 end
  end;
  if v_n is null or v_n not between 1 and 60 then
    raise exception 'invalid study aid' using errcode = '22023';
  end if;
  if p_kind = 'quiz' then
    if jsonb_typeof(p_answer_key -> 'answers') is distinct from 'array' or jsonb_array_length(p_answer_key -> 'answers') <> v_n
       or exists (
         select 1 from jsonb_array_elements(p_answer_key -> 'answers') as a
         where jsonb_typeof(a -> 'correct') is distinct from 'number' or (a ->> 'correct') not in ('0', '1', '2', '3')
       )
       or exists (
         select 1 from jsonb_array_elements(p_content -> 'questions') as q
         where jsonb_typeof(q -> 'options') is distinct from 'array' or jsonb_array_length(q -> 'options') <> 4
       ) then
      raise exception 'invalid quiz' using errcode = '22023';
    end if;
  elsif p_answer_key is not null then
    raise exception 'only quizzes have an answer key' using errcode = '22023';
  end if;

  insert into public.academic_items (tenant_id, course_id, user_id, kind, title, language, content, answer_key, sources, model)
  values (c.tenant_id, c.id, auth.uid(), p_kind, btrim(p_title), p_language, p_content, p_answer_key, p_sources, p_model)
  returning id into v_id;
  perform app.academic_record_usage(c.tenant_id, p_model, p_usage);
  return v_id;
end;
$$;

