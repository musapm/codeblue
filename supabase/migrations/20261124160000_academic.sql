-- Grade a quiz attempt. Answers: one per question, 0–3 or null (skipped). Returns the score
-- and, per question, whether it was right, the right option and the explanation.
create or replace function public.academic_submit_quiz(p_item uuid, p_answers jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  i public.academic_items;
  v_results jsonb;
  v_score integer;
  v_total integer;
begin
  select * into i from public.academic_items where id = p_item;
  if i.id is null or i.user_id <> auth.uid() or not app.can_view_course(i.course_id) then
    raise exception 'not authorized' using errcode = '42501';
  end if;
  if i.kind <> 'quiz' then
    raise exception 'not a quiz' using errcode = '22023';
  end if;
  v_total := jsonb_array_length(i.content -> 'questions');
  if jsonb_typeof(p_answers) is distinct from 'array' or jsonb_array_length(p_answers) <> v_total
     or exists (
       select 1 from jsonb_array_elements(p_answers) as a
       where not (jsonb_typeof(a) = 'null' or (jsonb_typeof(a) = 'number' and a::text in ('0', '1', '2', '3')))
     ) then
    raise exception 'one answer per question' using errcode = '22023';
  end if;

  select jsonb_agg(jsonb_build_object(
           'correct', coalesce(q.given::text = q.key ->> 'correct', false),
           'given', q.given,
           'answer', (q.key ->> 'correct')::integer,
           'explanation', q.key ->> 'explanation',
           'document_id', i.sources -> (app.try_int(q.question -> 'source' ->> 'm')) ->> 'document_id'
         ) order by q.idx),
         count(*) filter (where q.given::text = q.key ->> 'correct')
  into v_results, v_score
  from (
    select x.ord - 1 as idx, x.question, i.answer_key -> 'answers' -> (x.ord - 1)::integer as key,
           nullif(p_answers -> (x.ord - 1)::integer, 'null'::jsonb) as given
    from jsonb_array_elements(i.content -> 'questions') with ordinality as x (question, ord)
  ) as q;

  insert into public.academic_quiz_attempts (tenant_id, item_id, course_id, user_id, answers, results, score, total)
  values (i.tenant_id, i.id, i.course_id, auth.uid(), p_answers,
          (select jsonb_agg(jsonb_build_object('correct', r -> 'correct', 'document_id', r -> 'document_id')) from jsonb_array_elements(v_results) as r),
          v_score, v_total);
  return jsonb_build_object('score', v_score, 'total', v_total, 'results', v_results);
end;
$$;

-- The latest graded attempt of a quiz (with the answers), or null before the first attempt.
create or replace function public.academic_quiz_review(p_item uuid)
