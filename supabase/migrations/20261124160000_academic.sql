-- Progress on one's own flashcards ({"known": [card indexes]}) or study plan ({"done": [session indexes]}).
create or replace function public.academic_update_progress(p_item uuid, p_state jsonb)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  i public.academic_items;
  v_key text;
  v_n integer;
begin
  select * into i from public.academic_items where id = p_item;
  if i.id is null or i.user_id <> auth.uid() or not app.can_view_course(i.course_id) then
    raise exception 'not authorized' using errcode = '42501';
  end if;
  v_key := case i.kind when 'flashcards' then 'known' when 'study_plan' then 'done' end;
  v_n := case i.kind when 'flashcards' then jsonb_array_length(i.content -> 'cards') when 'study_plan' then jsonb_array_length(i.content -> 'sessions') end;
  if v_key is null or jsonb_typeof(p_state) is distinct from 'object'
     or (select count(*) from jsonb_object_keys(p_state)) <> 1 or not (p_state ? v_key)
     or jsonb_typeof(p_state -> v_key) is distinct from 'array'
     or exists (
       select 1 from jsonb_array_elements(p_state -> v_key) as e
       where jsonb_typeof(e) <> 'number' or app.try_int(e::text) is null or app.try_int(e::text) not between 0 and v_n - 1
     ) then
    raise exception 'invalid progress' using errcode = '22023';
  end if;
