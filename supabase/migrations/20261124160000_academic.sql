-- UniAgent AI · Phase 9 · Migration 15: academic assistant (courses, materials, study aids).
--
-- * Courses belong to a university. Academic managers (academic.manage) create them and assign
--   instructors; instructors manage their own courses; students join with a course code.
--   A new system role "Faculty member" gives teaching staff academic access.
-- * Course materials are knowledge documents with course_id set (always visibility
--   'restricted'): the same upload, extraction and chunking pipeline, but readable only by the
--   course's teachers and its enrolled students (published materials). They never appear in
--   the university knowledge base or in the general assistant's answers.
-- * Study aids (summaries, practice quizzes, flashcards, study plans) are generated by AI from
--   the course materials, per course only when the course has the tools switched on, and are
--   private to the student who made them. Quiz answers stay in the database until submitted.
-- * Instructors see class-level figures only; quiz accuracy per material is shown only when at
--   least 5 students contributed. Nobody sees another student's study aids or scores.
-- * AI usage is booked as feature 'academic_agent' with its own monthly budget and a daily
--   limit per person (academic_settings).

-- ---------------------------------------------------------------------------
-- Faculty member role (template for new universities, and added to existing ones)
-- ---------------------------------------------------------------------------

insert into app.role_templates (key, name, description, sort_order)
values ('faculty', 'Faculty member', 'Teaches courses: course materials and study tools', 9)
on conflict (key) do nothing;

insert into app.role_template_permissions (role_key, permission_key)
select 'faculty', p
from unnest(array[
  'tenant.settings.read', 'tenant.features.read', 'knowledge.read_public', 'knowledge.read_internal',
  'assistant.use', 'assistant.staff.use', 'tickets.create', 'tickets.read_own', 'academic.use'
]) as p
on conflict do nothing;

insert into public.roles (tenant_id, key, name, description, is_system)
select t.id, 'faculty', 'Faculty member', 'Teaches courses: course materials and study tools', true
from public.tenants t
on conflict (tenant_id, key) do nothing;

insert into public.role_permissions (tenant_id, role_id, permission_key)
select r.tenant_id, r.id, rtp.permission_key
from public.roles r
join app.role_template_permissions rtp on rtp.role_key = r.key
where r.key = 'faculty' and r.is_system
on conflict do nothing;

