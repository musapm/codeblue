create or replace function public.academic_begin_upload(
  p_course uuid,
  p_document uuid,
  p_file_name text,
  p_mime_type text,
  p_size_bytes bigint,
  p_meta jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  c public.courses;
  v_document uuid := p_document;
  v_version uuid;
  v_no integer;
  v_path text;
  v_ext text;
begin
  select * into c from public.courses where id = p_course;
  if c.id is null or not app.can_teach_course(c.id) then
    raise exception 'not authorized' using errcode = '42501';
  end if;
  if c.status = 'archived' then
    raise exception 'course is archived' using errcode = '55000';
  end if;

  if v_document is null then
    if nullif(btrim(p_meta ->> 'title'), '') is null then
      raise exception 'title required' using errcode = '22023';
    end if;
    insert into public.knowledge_documents (tenant_id, title, title_ar, description, language, visibility, course_id, created_by)
    values (c.tenant_id, btrim(p_meta ->> 'title'), nullif(btrim(p_meta ->> 'title_ar'), ''), nullif(btrim(p_meta ->> 'description'), ''),
            coalesce(nullif(p_meta ->> 'language', ''), 'en'), 'restricted', c.id, auth.uid())
    returning id into v_document;
  else
    if not exists (select 1 from public.knowledge_documents d where d.id = v_document and d.course_id = c.id) then
      raise exception 'not authorized' using errcode = '42501';
    end if;
    if exists (
      select 1 from public.knowledge_document_versions v
      where v.document_id = v_document and v.status in ('uploading', 'queued', 'processing')
        and v.created_at > now() - interval '1 hour'
    ) then
      raise exception 'another version is still being processed' using errcode = '55P03';
    end if;
  end if;

  select coalesce(max(v.version_no), 0) + 1 into v_no from public.knowledge_document_versions v where v.document_id = v_document;
  v_ext := case p_mime_type
    when 'application/pdf' then 'pdf'
    when 'application/vnd.openxmlformats-officedocument.wordprocessingml.document' then 'docx'
    when 'text/plain' then 'txt'
    when 'text/csv' then 'csv'
    else 'bin'
  end;
  v_path := c.tenant_id::text || '/' || v_document::text || '/v' || v_no || '/source.' || v_ext;

  insert into public.knowledge_document_versions (tenant_id, document_id, version_no, storage_path, file_name, mime_type, size_bytes, uploaded_by)
  values (c.tenant_id, v_document, v_no, v_path, left(btrim(p_file_name), 255), p_mime_type, p_size_bytes, auth.uid())
  returning id into v_version;

  return jsonb_build_object('document_id', v_document, 'version_id', v_version, 'version_no', v_no, 'storage_path', v_path);
end;
$$;

