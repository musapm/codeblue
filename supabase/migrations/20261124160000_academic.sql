create or replace function public.academic_create_course(
  p_tenant_slug text,
  p_code text,
  p_title text,
  p_title_ar text,
  p_description text,
  p_department uuid,
  p_term text
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_tenant uuid := app.tenant_id_for_slug(p_tenant_slug);
  v_id uuid;
begin
  if v_tenant is null or not app.has_permission(v_tenant, 'academic.manage') or not app.tenant_has_feature(v_tenant, 'academic_agent') then
    raise exception 'not authorized' using errcode = '42501';
  end if;
  insert into public.courses (tenant_id, code, title, title_ar, description, department_id, term, join_code, created_by)
  values (v_tenant, upper(btrim(p_code)), btrim(p_title), nullif(btrim(p_title_ar), ''), nullif(btrim(p_description), ''),
          p_department, nullif(btrim(p_term), ''), app.unique_join_code(v_tenant), auth.uid())
  returning id into v_id;
  insert into public.academic_settings (tenant_id) values (v_tenant) on conflict (tenant_id) do nothing;
  return v_id;
end;
$$;

-- Course details and status: academic managers.
create or replace function public.academic_update_course(
  p_course uuid,
  p_code text,
  p_title text,
  p_title_ar text,
  p_description text,
  p_department uuid,
  p_term text,
  p_status text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  c public.courses;
begin
  select * into c from public.courses where id = p_course;
  if c.id is null or not app.has_permission(c.tenant_id, 'academic.manage') or not app.tenant_has_feature(c.tenant_id, 'academic_agent') then
    raise exception 'not authorized' using errcode = '42501';
  end if;
  update public.courses
  set code = upper(btrim(p_code)), title = btrim(p_title), title_ar = nullif(btrim(p_title_ar), ''),
      description = nullif(btrim(p_description), ''), department_id = p_department, term = nullif(btrim(p_term), ''), status = p_status
  where id = c.id;
end;
$$;

-- The study tools of one course: its teachers.
create or replace function public.academic_update_course_ai(
  p_course uuid,
  p_ai_enabled boolean,
  p_summaries boolean,
  p_quizzes boolean,
  p_flashcards boolean,
  p_study_plans boolean,
  p_instructions text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  c public.courses;
begin
  select * into c from public.courses where id = p_course;
  if c.id is null or not app.can_teach_course(c.id) then
    raise exception 'not authorized' using errcode = '42501';
  end if;
  if c.status = 'archived' then
    raise exception 'course is archived' using errcode = '55000';
  end if;
  update public.courses
  set ai_enabled = coalesce(p_ai_enabled, false), allow_summaries = coalesce(p_summaries, false), allow_quizzes = coalesce(p_quizzes, false),
      allow_flashcards = coalesce(p_flashcards, false), allow_study_plans = coalesce(p_study_plans, false),
      instructions = nullif(btrim(p_instructions), '')
  where id = c.id;
end;
$$;

-- Open or close joining with the code, optionally with a new code. Returns the current code.
create or replace function public.academic_set_join(p_course uuid, p_open boolean, p_rotate boolean)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  c public.courses;
  v_code text;
begin
  select * into c from public.courses where id = p_course;
  if c.id is null or not app.can_teach_course(c.id) then
    raise exception 'not authorized' using errcode = '42501';
  end if;
  v_code := case when coalesce(p_rotate, false) then app.unique_join_code(c.tenant_id) else c.join_code end;
